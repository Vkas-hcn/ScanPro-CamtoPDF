def xml_escape(s: str) -> str:
    return (
        s.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("'", r"\'")
        .replace('"', "&quot;")
    )


for loc, pairs in missing.items():
    path = root / f"values-{loc}" / "strings.xml"
    text = path.read_text(encoding="utf-8")
    if "uninstall_system_failed" in text:
        print(f"{loc}: strings already updated")
    else:
        block = "\n".join(
            f'    <string name="{k}">{xml_escape(v)}</string>' for k, v in pairs.items()
        )
        text = text.replace("</resources>", block + "\n</resources>")
        path.write_text(text, encoding="utf-8")
        print(f"{loc}: appended {len(pairs)} strings")

